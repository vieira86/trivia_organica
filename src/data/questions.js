export function shuffleArray(array) {
  const result = [...array]
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[result[i], result[j]] = [result[j], result[i]]
  }
  return result
}

/** Embaralha as alternativas de uma pergunta, preservando qual é a correta. */
export function shuffleQuestionOptions(question) {
  const order = shuffleArray(question.options.map((_, index) => index))
  return {
    options: order.map(originalIndex => question.options[originalIndex]),
    correctIndex: order.indexOf(question.correct)
  }
}

/**
 * Sorteia uma pergunta de uma área específica, evitando repetir as últimas
 * `recentIds` sempre que possível. Se `areaId` for omitido, sorteia de todo o banco.
 * Quando o pool de "não recentes" esvazia, volta a considerar todas as perguntas da área.
 */
export function pickRandomQuestion(recentIds = [], areaId = null) {
  const basePool = areaId ? QUESTIONS.filter(q => q.area === areaId) : QUESTIONS
  const pool = basePool.filter(q => !recentIds.includes(q.id))
  const source = pool.length > 0 ? pool : basePool
  return source[Math.floor(Math.random() * source.length)]
}

